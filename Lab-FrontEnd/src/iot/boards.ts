const BOARD_W = 216
const BOARD_H = 296

function makeTwoColumnPins(
  left: Array<{ id: string; label: string; voltage: 0 | 3.3 | 5; kind: PinDef['kind']; gpio?: number }>,
  right: Array<{ id: string; label: string; voltage: 0 | 3.3 | 5; kind: PinDef['kind']; gpio?: number }>,
): PinDef[] {
  return [
    ...left.map((p, i) => ({ ...p, x: 11, y: 54 + i * 24, side: 'left' as const })),
    ...right.map((p, i) => ({ ...p, x: BOARD_W - 11, y: 54 + i * 24, side: 'right' as const })),
  ]
}

